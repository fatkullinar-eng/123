// Generate a precise uninstall manifest: never recursively delete the user's folder.
const fs = require("node:fs");
const path = require("node:path");
module.exports = async function afterPack(context) {
  if (context.electronPlatformName !== "win32") return;
  const files = [],
    directories = [];
  function walk(dir, relative = "") {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const next = path.join(relative, entry.name);
      if (entry.isDirectory()) {
        directories.push(next);
        walk(path.join(dir, entry.name), next);
      } else files.push(next);
    }
  }
  walk(context.appOutDir);
  const escape = (value) =>
    value.replaceAll("$", "$$").replaceAll('"', '$\\"').replaceAll("/", "\\");
  const lines = files
    .filter((file) => file !== "Bar Estimate.exe")
    .map((file) => `Delete "$INSTDIR\\${escape(file)}"`);
  lines.push(
    ...directories
      .sort((a, b) => b.split(path.sep).length - a.split(path.sep).length)
      .map((dir) => `RMDir "$INSTDIR\\${escape(dir)}"`),
  );
  const target = path.join(
    context.packager.projectDir,
    "build",
    "uninstall-files.nsh",
  );
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(
    target,
    "; Generated by scripts/after-pack.cjs\n" + lines.join("\n") + "\n",
  );
};
